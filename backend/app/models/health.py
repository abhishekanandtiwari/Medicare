from datetime import datetime
from sqlalchemy import Column, Integer, String, Float, DateTime, ForeignKey, Text, Boolean
from sqlalchemy.orm import relationship
from app.database import Base

class HealthMetric(Base):
    __tablename__ = "health_metrics"

    id = Column(Integer, primary_key=True, index=True)
    patient_id = Column(Integer, ForeignKey("patients.id", ondelete="CASCADE"), nullable=False)
    metric_type = Column(String(50), nullable=False, index=True) 
    # e.g., "heart_rate", "bp_systolic", "bp_diastolic", "blood_glucose", "weight", "temperature", "water_ml", "sleep_hours", "steps"
    value = Column(Float, nullable=False)
    unit = Column(String(20), nullable=False)  # "bpm", "mmHg", "mg/dL", "kg", "°C", "ml", "hours", "steps"
    recorded_at = Column(DateTime, default=datetime.utcnow, index=True)
    notes = Column(String(255), nullable=True)

    patient = relationship("PatientProfile", back_populates="health_metrics")

class HealthRecord(Base):
    __tablename__ = "health_records"

    id = Column(Integer, primary_key=True, index=True)
    patient_id = Column(Integer, ForeignKey("patients.id", ondelete="CASCADE"), nullable=False)
    category = Column(String(50), nullable=False, index=True)
    # e.g., "lab_report", "prescription", "imaging", "vaccination", "certificate", "other"
    title = Column(String(255), nullable=False)
    file_url = Column(String(500), nullable=False)
    file_type = Column(String(50), nullable=False)  # "pdf", "jpg", "png", "txt"
    file_size_kb = Column(Float, default=0.0)
    ai_summary = Column(Text, nullable=True)  # JSON or markdown text summary generated by AI
    ai_questions = Column(Text, nullable=True) # JSON list of questions for doctor
    doctor_notes = Column(Text, nullable=True)
    uploaded_at = Column(DateTime, default=datetime.utcnow)

    patient = relationship("PatientProfile", back_populates="health_records")

class Medication(Base):
    __tablename__ = "medications"

    id = Column(Integer, primary_key=True, index=True)
    patient_id = Column(Integer, ForeignKey("patients.id", ondelete="CASCADE"), nullable=False)
    medicine_name = Column(String(255), nullable=False)
    dosage = Column(String(100), nullable=False)  # e.g., "500mg", "1 tablet"
    frequency = Column(String(100), nullable=False) # e.g., "Once daily", "Twice daily after meals"
    reminder_time = Column(String(20), nullable=False) # e.g., "08:00 AM", "20:00"
    start_date = Column(String(20), nullable=True)
    end_date = Column(String(20), nullable=True)
    refills_left = Column(Integer, default=1)
    notes = Column(Text, nullable=True)
    is_active = Column(Boolean, default=True)
    created_at = Column(DateTime, default=datetime.utcnow)

    patient = relationship("PatientProfile", back_populates="medications")
    logs = relationship("MedicationLog", back_populates="medication", cascade="all, delete-orphan")

class MedicationLog(Base):
    __tablename__ = "medication_logs"

    id = Column(Integer, primary_key=True, index=True)
    medication_id = Column(Integer, ForeignKey("medications.id", ondelete="CASCADE"), nullable=False)
    patient_id = Column(Integer, ForeignKey("patients.id", ondelete="CASCADE"), nullable=False)
    scheduled_time = Column(String(30), nullable=False)
    logged_at = Column(DateTime, default=datetime.utcnow)
    status = Column(String(20), default="taken") # "taken", "skipped"

    medication = relationship("Medication", back_populates="logs")
